export type Lang = "it" | "en";

let current: Lang = navigator.language?.toLowerCase().startsWith("it") ? "it" : "en";

/** The backend decides the language (session locale: Italian or English), so UI and messages agree. */
export async function initLanguage(): Promise<void> {
  try {
    const code = await invoke<string>("app_language");
    current = code === "it" ? "it" : "en";
  } catch {
    // Outside Tauri (tests, previews) the browser language is the best guess.
  }
  document.documentElement.lang = current;
}

export function language(): Lang {
  return current;
}

export function t(key: Key, vars?: Record<string, string | number>): string {
  const template: string = current === "it" ? it[key] : en[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}

export function formatBytes(n: number | null | undefined): string {
  if (n == null) return "—";
  const units = ["B", "KiB", "MiB", "GiB", "TiB"];
  let v = n;
  let i = 0;
  while (v >= 1024 && i < units.length - 1) {
    v /= 1024;
    i++;
  }
  return `${new Intl.NumberFormat(current, { maximumFractionDigits: i === 0 ? 0 : 1 }).format(v)} ${units[i]}`;
}
